        private const float DOUBLE_CLICK_TIME = 0.3f;
        private double _lastClickTime;
        private string _lastClickPath;

        private int _dragRefCount = 0;
        private float _lastDragTime = -DRAG_TIMEOUT;
        private const float DRAG_TIMEOUT = 10.0f; // safeguard

        private void Handle(string path)
        {
            var now = Time.realtimeSinceStartupAsDouble;
            if (_lastClickPath == path && now - _lastClickTime < DOUBLE_CLICK_TIME)
                _selectionHandler.HandleButtonDoubleClick(path);
            else
                _selectionHandler.HandleButton(path, allowMultiSelect: true);
            _lastClickTime = now;
            _lastClickPath = path;
        }

        public void HandleRow(int row)
        {
            _selectionHandler.HandleRowButton(row);
        }

        public void HandleCol(string col)
        {
            _selectionHandler.HandleColButton(col);
        }

        public void HandleFormulaFieldChanged()
        {
            _selectionHandler.HandleFormulaFieldChanged();
        }

        private void BeginDragCell(string path)
        {
            if (Input.GetKey(KeyCode.LeftShift) || Input.GetKey(KeyCode.RightShift))
                return;

            _dragRefCount++;
            if (_dragRefCount == 1)
            {
                _selectionHandler.HandleButton(path, allowMultiSelect: false);
                _lastDragTime = Time.realtimeSinceStartup;
            }
        }

        private void EndDragCell(string path) // TODO: Check path?
        {
            _dragRefCount--;
            if (_dragRefCount <= 0)
            {
                _dragRefCount = 0;
            }
        }

        private void PointerEnter(string path)
        {
            var timeout = Time.realtimeSinceStartup - _lastDragTime >= DRAG_TIMEOUT;
            if (_dragRefCount > 0 && !timeout)
            {
                _selectionHandler.HandleButtonMultiSelectEnter(path);
            }
            else if (timeout)
            {
                // safeguard
                _dragRefCount = 0;
            }
        }

        public void HandleCopyButton()
        {
            _selectionHandler.HandleCopyButton();
        }

        private void HandleColorButton(int index)
        {
            _styleHandler.HandleColorButton(index);
        }

